[[nodiscard]] std::string summarize_smtp_capabilities(const mailxx::smtp::client& client)
{
    std::ostringstream oss;
    const auto size_limit = client.get_size_limit();
    oss << "PIPELINING=" << (client.supports_pipelining() ? "yes" : "no")
        << " SIZE=";
    if (size_limit.has_limit())
        oss << size_limit.max_size;
    else
        oss << "unknown";
    oss << " 8BITMIME=" << (client.supports_8bitmime() ? "yes" : "no")
        << " SMTPUTF8=" << (client.supports_smtputf8() ? "yes" : "no")
        << " DSN=" << (client.supports_dsn() ? "yes" : "no");
    return oss.str();
}

