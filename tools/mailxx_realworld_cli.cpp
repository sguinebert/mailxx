mailxx::asio::awaitable<int> run_smtp_suite(const smtp_cli_options& options, scenario_recorder& recorder)
{
    const auto tls_mode = parse_tls_mode(options.tls.tls_mode);
    const std::string port = options.tls.port.empty() ? default_smtp_port(tls_mode) : options.tls.port;
    const std::string sni = options.tls.sni.empty() ? options.tls.host : options.tls.sni;

    MAILXX_LOG_INFO("CLI", "Starting SMTP suite with " << smtp_connection_summary(options, port));

    mailxx::smtp::options client_options;
    apply_shared_security_options(client_options, options.tls, options.allow_cleartext_auth, options.require_tls_for_auth);
    mailxx::smtp::client client(co_await mailxx::asio::this_coro::executor, client_options);
    mailxx::asio::ssl::context tls_ctx(mailxx::asio::ssl::context::tls_client);

    bool connected = false;
    bool greeted = false;

    auto connect_res = co_await client.connect(options.tls.host, port, tls_mode,
        tls_mode == mailxx::net::tls_mode::none ? nullptr : &tls_ctx, sni);
    if (!record_result(recorder, "connect", std::move(connect_res), [&]
        {
            connected = true;
            return "Connected to " + options.tls.host + ":" + port;
        }))
    {
        co_return recorder.exit_code();
    }

    auto greeting_res = co_await client.read_greeting();
    if (!record_result(recorder, "greeting", std::move(greeting_res), [&]
        {
            greeted = true;
            return "SMTP greeting read successfully";
        }))
    {
        co_return recorder.exit_code();
    }

    auto ehlo_res = co_await client.ehlo(options.hello_domain);
    if (!record_result(recorder, "ehlo", std::move(ehlo_res), [&]
        {
            return "EHLO completed with domain " + options.hello_domain;
        }))
    {
        co_return recorder.exit_code();
    }
    recorder.pass("capabilities_pre_tls", summarize_smtp_capabilities(client));

    if (tls_mode == mailxx::net::tls_mode::starttls)
    {
        auto starttls_res = co_await client.start_tls(tls_ctx, sni);
        if (!record_result(recorder, "starttls", std::move(starttls_res), [&]
            {
                return "TLS upgrade completed";
            }))
        {
            co_return recorder.exit_code();
        }

        auto ehlo_tls_res = co_await client.ehlo(options.hello_domain);
        if (!record_result(recorder, "ehlo_post_tls", std::move(ehlo_tls_res), [&]
            {
                return "EHLO repeated after STARTTLS";
            }))
        {
            co_return recorder.exit_code();
        }
        recorder.pass("capabilities_post_tls", summarize_smtp_capabilities(client));
    }

    if (!options.username.empty() && !options.secret.empty())
    {
        auto auth_res = co_await client.authenticate(
            options.username,
            options.secret,
            parse_smtp_auth_method(options.auth_method));
        if (!record_result(recorder, "auth", std::move(auth_res), [&]
            {
                return "Authenticated as " + options.username;
            }))
        {
            co_return recorder.exit_code();
        }
    }
    else
    {
        recorder.skip("auth", "No --username/--secret provided");
    }

    auto noop_res = co_await client.noop();
    if (!record_result(recorder, "noop", std::move(noop_res), [](const mailxx::smtp::reply& reply)
        {
            return summarize_smtp_reply(reply);
        }))
    {
        co_return recorder.exit_code();
    }

    auto rset_res = co_await client.rset();
    if (!record_result(recorder, "rset", std::move(rset_res), [](const mailxx::smtp::reply& reply)
        {
            return summarize_smtp_reply(reply);
        }))
    {
        co_return recorder.exit_code();
    }

    const auto envelope = build_envelope(options);
    const bool can_send = !envelope.mail_from.empty() && !envelope.rcpt_to.empty();
    if (!can_send)
    {
        recorder.skip("send_simple", "Missing sender/recipient. Set --from/--to or use an email-like --username");
        recorder.skip("send_pipelined", "Missing sender/recipient");
        recorder.skip("send_streaming", "Missing sender/recipient");
        recorder.skip("send_progress", "Missing sender/recipient");
        recorder.skip("send_utf8_content", "Missing sender/recipient");
        recorder.skip("send_attachment", "Missing sender/recipient");
        recorder.skip("send_dsn", "Missing sender/recipient");
    }
    else
    {
        auto simple_message = build_message(options, "send_simple");
        if (!simple_message)
        {
            (void)recorder.fail("send_simple_build", simple_message.error());
            co_return recorder.exit_code();
        }
        auto send_res = co_await client.send(*simple_message);
        if (!record_result(recorder, "send_simple", std::move(send_res), [](const mailxx::smtp::reply& reply)
            {
                return summarize_smtp_reply(reply);
            }))
        {
            co_return recorder.exit_code();
        }

        if (client.supports_pipelining())
        {
            auto pipelined_message = build_message(options, "send_pipelined");
            if (!pipelined_message)
            {
                (void)recorder.fail("send_pipelined_build", pipelined_message.error());
                co_return recorder.exit_code();
            }
            auto pipelined_res = co_await client.send_pipelined(*pipelined_message, envelope);
            if (!record_result(recorder, "send_pipelined", std::move(pipelined_res), [](const mailxx::smtp::reply& reply)
                {
                    return summarize_smtp_reply(reply);
                }))
            {
                co_return recorder.exit_code();
            }
        }
        else
        {
            recorder.skip("send_pipelined", "Server did not advertise PIPELINING");
        }

        auto streaming_message = build_message(options, "send_streaming", false, {}, true);
        if (!streaming_message)
        {
            (void)recorder.fail("send_streaming_build", streaming_message.error());
            co_return recorder.exit_code();
        }
        auto streaming_res = co_await client.send_streaming(envelope, *streaming_message);
        if (!record_result(recorder, "send_streaming", std::move(streaming_res), [](const mailxx::smtp::reply& reply)
            {
                return summarize_smtp_reply(reply);
            }))
        {
            co_return recorder.exit_code();
        }

        auto progress_message = build_message(options, "send_progress", false, {}, true);
        if (!progress_message)
        {
            (void)recorder.fail("send_progress_build", progress_message.error());
            co_return recorder.exit_code();
        }
        auto progress_res = co_await client.send_with_progress(
            *progress_message,
            envelope,
            [](const mailxx::smtp::progress_info_t& progress)
            {
                MAILXX_LOG_DEBUG("CLI", "SMTP progress bytes=" << progress.bytes_transferred
                    << " total=" << progress.total_bytes
                    << " percent=" << progress.percent());
            });
        if (!record_result(recorder, "send_progress", std::move(progress_res), [](const mailxx::smtp::reply& reply)
            {
                return summarize_smtp_reply(reply);
            }))
        {
            co_return recorder.exit_code();
        }

        auto utf8_message = build_message(options, "send_utf8_content", true);
        if (!utf8_message)
        {
            (void)recorder.fail("send_utf8_content_build", utf8_message.error());
            co_return recorder.exit_code();
        }
        auto utf8_res = co_await client.send(*utf8_message, envelope);
        if (!record_result(recorder, "send_utf8_content", std::move(utf8_res), [](const mailxx::smtp::reply& reply)
            {
                return summarize_smtp_reply(reply);
            }))
        {
            co_return recorder.exit_code();
        }

        const auto attachments = effective_attachments(options);
        if (!attachments.empty())
        {
            auto attachment_message = build_message(options, "send_attachment", false, attachments);
            if (!attachment_message)
            {
                (void)recorder.fail("send_attachment_build", attachment_message.error());
                co_return recorder.exit_code();
            }
            auto attachment_res = co_await client.send(*attachment_message, envelope);
            if (!record_result(recorder, "send_attachment", std::move(attachment_res), [&](const mailxx::smtp::reply& reply)
                {
                    std::vector<std::string> names;
                    for (const auto& file : attachments)
                        names.push_back(file.filename().string());
                    return summarize_smtp_reply(reply) + " files=" + join_strings(names);
                }))
            {
                co_return recorder.exit_code();
            }
        }
        else
        {
            recorder.skip("send_attachment", "No --attachment provided and bundled sample files were not found");
        }

        if (client.supports_dsn())
        {
            auto dsn_message = build_message(options, "send_dsn");
            if (!dsn_message)
            {
                (void)recorder.fail("send_dsn_build", dsn_message.error());
                co_return recorder.exit_code();
            }
            mailxx::smtp::envelope_dsn env(envelope, mailxx::smtp::dsn_options::on_failure());
            auto dsn_res = co_await client.send(*dsn_message, env);
            if (!record_result(recorder, "send_dsn", std::move(dsn_res), [](const mailxx::smtp::reply& reply)
                {
                    return summarize_smtp_reply(reply);
                }))
            {
                co_return recorder.exit_code();
            }
        }
        else
        {
            recorder.skip("send_dsn", "Server did not advertise DSN");
        }
    }

    if (connected && greeted)
    {
        auto quit_res = co_await client.quit();
        if (!record_result(recorder, "quit", std::move(quit_res), [](const mailxx::smtp::reply& reply)
            {
                return summarize_smtp_reply(reply);
            }))
        {
            co_return recorder.exit_code();
        }
    }

    co_return recorder.exit_code();
}

mailxx::asio::awaitable<int> run_imap_suite(const imap_cli_options& options, scenario_recorder& recorder)
{
    const auto tls_mode = parse_tls_mode(options.tls.tls_mode);
    const std::string port = options.tls.port.empty() ? default_imap_port(tls_mode) : options.tls.port;
    const std::string sni = options.tls.sni.empty() ? options.tls.host : options.tls.sni;

    MAILXX_LOG_INFO("CLI", "Starting IMAP suite with " << imap_connection_summary(options, port));

    mailxx::imap::options client_options;
    apply_shared_security_options(client_options, options.tls, options.allow_cleartext_auth, options.require_tls_for_auth);
    mailxx::imap::client client(co_await mailxx::asio::this_coro::executor, client_options);
    mailxx::asio::ssl::context tls_ctx(mailxx::asio::ssl::context::tls_client);

    auto connect_res = co_await client.connect(options.tls.host, port, tls_mode,
        tls_mode == mailxx::net::tls_mode::none ? nullptr : &tls_ctx, sni);
    if (!record_result(recorder, "connect", std::move(connect_res), [&]
        {
            return "Connected to " + options.tls.host + ":" + port;
        }))
    {
        co_return recorder.exit_code();
    }

    auto greeting_res = co_await client.read_greeting();
    if (!record_result(recorder, "greeting", std::move(greeting_res), [](const mailxx::imap::response& response)
        {
            return summarize_imap_response(response);
        }))
    {
        co_return recorder.exit_code();
    }

    auto capability_res = co_await client.capability();
    if (!record_result(recorder, "capability_pre_tls", std::move(capability_res), [](const mailxx::imap::response& response)
        {
            return summarize_imap_response(response);
        }))
    {
        co_return recorder.exit_code();
    }

    if (tls_mode == mailxx::net::tls_mode::starttls)
    {
        auto starttls_res = co_await client.start_tls(tls_ctx, sni);
        if (!record_result(recorder, "starttls", std::move(starttls_res), [&]
            {
                return "TLS upgrade completed";
            }))
        {
            co_return recorder.exit_code();
        }

        auto capability_tls_res = co_await client.capability();
        if (!record_result(recorder, "capability_post_tls", std::move(capability_tls_res), [](const mailxx::imap::response& response)
            {
                return summarize_imap_response(response);
            }))
        {
            co_return recorder.exit_code();
        }
    }

    bool authenticated = false;
    if (!options.username.empty() && !options.secret.empty())
    {
        const auto method = parse_imap_auth_method(options.auth_method);
        if (method == mailxx::imap::auth_method::login)
        {
            auto login_res = co_await client.login(options.username, options.secret);
            if (!record_result(recorder, "auth", std::move(login_res), [&](const mailxx::imap::response& response)
                {
                    authenticated = true;
                    return summarize_imap_response(response);
                }))
            {
                co_return recorder.exit_code();
            }
        }
        else
        {
            mailxx::imap::credentials credentials{options.username, options.secret};
            auto auth_res = co_await client.authenticate(std::move(credentials), method);
            if (!record_result(recorder, "auth", std::move(auth_res), [&](const mailxx::imap::response& response)
                {
                    authenticated = true;
                    return summarize_imap_response(response);
                }))
            {
                co_return recorder.exit_code();
            }
        }
    }
    else
    {
        recorder.skip("auth", "No --username/--secret provided");
    }

    if (!authenticated)
    {
        recorder.skip("noop", "Skipped because IMAP authentication did not run");
        recorder.skip("list", "Skipped because IMAP authentication did not run");
        recorder.skip("select", "Skipped because IMAP authentication did not run");
        recorder.skip("search", "Skipped because IMAP authentication did not run");
        recorder.skip("fetch", "Skipped because IMAP authentication did not run");
    }
    else
    {
        auto noop_res = co_await client.noop();
        if (!record_result(recorder, "noop", std::move(noop_res), [](const mailxx::imap::response& response)
            {
                return summarize_imap_response(response);
            }))
        {
            co_return recorder.exit_code();
        }

        auto list_res = co_await client.list("", "*");
        if (!record_result(recorder, "list", std::move(list_res), [](const std::pair<mailxx::imap::response, std::vector<mailxx::imap::mailbox_folder>>& value)
            {
                std::vector<std::string> folders;
                for (const auto& folder : value.second)
                    folders.push_back(folder.name);
                std::ostringstream detail;
                detail << summarize_imap_response(value.first) << " folders=" << folders.size();
                if (!folders.empty())
                    detail << " [" << truncate_copy(join_strings(folders), 200) << ']';
                return detail.str();
            }))
        {
            co_return recorder.exit_code();
        }

        auto select_res = co_await client.select(options.mailbox);
        if (!record_result(recorder, "select", std::move(select_res), [](const std::pair<mailxx::imap::response, mailxx::imap::mailbox_stat>& value)
            {
                std::ostringstream detail;
                detail << summarize_imap_response(value.first) << ' ' << summarize_mailbox_stat(value.second);
                return detail.str();
            }))
        {
            co_return recorder.exit_code();
        }

        auto search_res = co_await client.uid_search(options.search);
        if (!record_result(recorder, "search", std::move(search_res), [](const std::vector<std::uint32_t>& ids)
            {
                std::ostringstream detail;
                detail << "uids=" << ids.size();
                if (!ids.empty())
                    detail << " first=" << ids.front();
                return detail.str();
            }))
        {
            co_return recorder.exit_code();
        }

        auto ids_res = co_await client.uid_search(options.search);
        if (!ids_res)
        {
            (void)recorder.fail("fetch_prepare", ids_res.error());
            co_return recorder.exit_code();
        }

        std::uint32_t selected_uid = 0;
        if (options.uid.has_value())
            selected_uid = *options.uid;
        else if (!ids_res->empty())
            selected_uid = ids_res->front();

        if (selected_uid == 0)
        {
            recorder.skip("fetch", "No UID available for fetch");
        }
        else
        {
            auto fetch_res = co_await client.uid_fetch_rfc822(selected_uid);
            if (!record_result(recorder, "fetch", std::move(fetch_res), [&](const mailxx::message& message)
                {
                    std::ostringstream detail;
                    detail << "uid=" << selected_uid << " subject=\"" << truncate_copy(message.subject()) << '"';
                    return detail.str();
                }))
            {
                co_return recorder.exit_code();
            }
        }
    }

    auto logout_res = co_await client.logout();
    if (!record_result(recorder, "logout", std::move(logout_res), [](const mailxx::imap::response& response)
        {
            return summarize_imap_response(response);
        }))
    {
        co_return recorder.exit_code();
    }

    co_return recorder.exit_code();
}

