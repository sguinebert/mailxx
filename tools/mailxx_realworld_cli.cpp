[[nodiscard]] mailxx::net::tls_options make_tls_options(const tls_cli_options& cli)
{
    mailxx::net::tls_options tls;
    tls.verify = cli.insecure ? mailxx::net::verify_mode::none : mailxx::net::verify_mode::peer;
    tls.verify_host = !cli.insecure;
    tls.use_default_verify_paths = cli.use_default_verify_paths;
    tls.ca_files = cli.ca_files;
    tls.ca_paths = cli.ca_paths;
    tls.allow_self_signed = cli.allow_self_signed;
    tls.allow_expired = cli.allow_expired;
    return tls;
}

template<typename Options>
void apply_shared_security_options(
    Options& options,
    const tls_cli_options& tls_cli,
    bool allow_cleartext_auth,
    bool require_tls_for_auth)
{
    options.default_sni = tls_cli.sni;
    options.auto_starttls = false;
    options.allow_cleartext_auth = allow_cleartext_auth;
    options.require_tls_for_auth = allow_cleartext_auth ? false : require_tls_for_auth;
    options.default_tls_mode = parse_tls_mode(tls_cli.tls_mode);
    options.redact_secrets_in_trace = true;
    options.tls = make_tls_options(tls_cli);
}

