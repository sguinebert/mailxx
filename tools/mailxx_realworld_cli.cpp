[[nodiscard]] std::string lower_copy(std::string value)
{
    std::transform(value.begin(), value.end(), value.begin(),
        [](unsigned char ch) { return static_cast<char>(std::tolower(ch)); });
    return value;
}

[[nodiscard]] std::string sanitize_inline(std::string value)
{
    std::replace(value.begin(), value.end(), '\r', ' ');
    std::replace(value.begin(), value.end(), '\n', ' ');
    return value;
}

[[nodiscard]] std::string truncate_copy(std::string_view value, std::size_t max_len = 140)
{
    std::string out(value);
    if (out.size() <= max_len)
        return sanitize_inline(std::move(out));
    out.resize(max_len);
    out += "...";
    return sanitize_inline(std::move(out));
}

[[nodiscard]] std::string join_strings(const std::vector<std::string>& values, std::string_view separator = ", ")
{
    std::ostringstream oss;
    for (std::size_t i = 0; i < values.size(); ++i)
    {
        if (i != 0)
            oss << separator;
        oss << values[i];
    }
    return oss.str();
}

[[nodiscard]] bool looks_like_email(std::string_view value)
{
    return value.find('@') != std::string_view::npos;
}

[[nodiscard]] std::string now_utc_string()
{
    const auto now = std::chrono::system_clock::now();
    const auto time = std::chrono::system_clock::to_time_t(now);
    std::tm tm_buf{};
#ifdef _WIN32
    gmtime_s(&tm_buf, &time);
#else
    gmtime_r(&time, &tm_buf);
#endif
    std::ostringstream oss;
    oss << std::put_time(&tm_buf, "%Y-%m-%d %H:%M:%S UTC");
    return oss.str();
}

[[nodiscard]] std::string scenario_status_to_string(scenario_status status)
{
    switch (status)
    {
        case scenario_status::passed: return "PASS";
        case scenario_status::failed: return "FAIL";
        case scenario_status::skipped: return "SKIP";
    }
    return "UNKNOWN";
}

class log_sink
{
public:
    log_sink(std::string log_file, bool show_source)
        : show_source_(show_source)
    {
        if (!log_file.empty())
        {
            std::filesystem::path path(log_file);
            if (path.has_parent_path())
                std::filesystem::create_directories(path.parent_path());
            file_.open(path, std::ios::out | std::ios::trunc);
            if (!file_)
                throw std::runtime_error("Unable to open log file: " + path.string());
        }
    }

    void write(const mailxx::log::entry& entry)
    {
        const std::string line = format(entry);
        std::lock_guard lock(mutex_);
        std::cerr << line << '\n';
        if (file_)
        {
            file_ << line << '\n';
            file_.flush();
        }
    }

private:
    [[nodiscard]] std::string format_timestamp(const std::chrono::system_clock::time_point& tp) const
    {
        const auto time = std::chrono::system_clock::to_time_t(tp);
        const auto ms = std::chrono::duration_cast<std::chrono::milliseconds>(tp.time_since_epoch()) % 1000;
        std::tm tm_buf{};
#ifdef _WIN32
        localtime_s(&tm_buf, &time);
#else
        localtime_r(&time, &tm_buf);
#endif

        std::ostringstream oss;
        oss << std::put_time(&tm_buf, "%Y-%m-%d %H:%M:%S")
            << '.' << std::setw(3) << std::setfill('0') << ms.count();
        return oss.str();
    }

    [[nodiscard]] std::string thread_id_string() const
    {
        std::ostringstream oss;
        oss << std::this_thread::get_id();
        return oss.str();
    }

    [[nodiscard]] std::string format(const mailxx::log::entry& entry) const
    {
        std::ostringstream oss;
        oss << '[' << format_timestamp(entry.timestamp) << "] "
            << '[' << mailxx::log::level_to_string(entry.lvl) << "] "
            << "[tid=" << thread_id_string() << "] ";

        if (entry.trace_info)
        {
            const char* direction = entry.trace_info->dir == mailxx::log::direction::send ? ">>>" : "<<<";
            oss << entry.trace_info->protocol << ' ' << direction << ' '
                << truncate_copy(entry.trace_info->data, 500);
        }
        else
        {
            oss << entry.message;
        }

        if (show_source_)
            oss << " (" << entry.location.file_name() << ':' << entry.location.line() << ')';

        return oss.str();
    }

    bool show_source_{true};
    std::mutex mutex_;
    std::ofstream file_;
};

class scenario_recorder
{
public:
    scenario_recorder(std::string suite_name, bool stop_on_error)
        : suite_name_(std::move(suite_name)),
          stop_on_error_(stop_on_error)
    {
    }

    void pass(std::string name, std::string detail)
    {
        results_.push_back({std::move(name), scenario_status::passed, std::move(detail)});
        const auto& result = results_.back();
        MAILXX_LOG_INFO("CLI", result.name << " ok - " << result.detail);
    }

    void skip(std::string name, std::string detail)
    {
        results_.push_back({std::move(name), scenario_status::skipped, std::move(detail)});
        const auto& result = results_.back();
        MAILXX_LOG_WARN("CLI", result.name << " skipped - " << result.detail);
    }

    [[nodiscard]] bool fail(std::string name, const mailxx::error_info& err)
    {
        std::ostringstream detail;
        detail << mailxx::to_string(err.code) << " - " << err.message;
        if (!err.sys.message().empty())
            detail << " [sys=" << err.sys.message() << ']';

        results_.push_back({std::move(name), scenario_status::failed, detail.str()});
        const auto& result = results_.back();
        MAILXX_LOG_ERROR("CLI", result.name << " failed - " << result.detail);
        if (!err.detail.empty())
            MAILXX_LOG_DEBUG("CLI", result.name << " detail=" << sanitize_inline(err.detail));
        MAILXX_LOG_DEBUG("CLI", result.name << " where=" << err.where.file_name() << ':' << err.where.line());
        return !stop_on_error_;
    }

    [[nodiscard]] bool has_failures() const
    {
        return std::any_of(results_.begin(), results_.end(), [](const scenario_result& result)
        {
            return result.status == scenario_status::failed;
        });
    }

    [[nodiscard]] int exit_code() const
    {
        return has_failures() ? 2 : 0;
    }

    void print_summary() const
    {
        std::size_t passed = 0;
        std::size_t failed = 0;
        std::size_t skipped = 0;

        for (const auto& result : results_)
        {
            switch (result.status)
            {
                case scenario_status::passed: ++passed; break;
                case scenario_status::failed: ++failed; break;
                case scenario_status::skipped: ++skipped; break;
            }
        }

        std::cout << "\n=== " << suite_name_ << " Summary ===\n";
        for (const auto& result : results_)
            std::cout << scenario_status_to_string(result.status) << "  " << result.name << "  " << result.detail << '\n';
        std::cout << "Totals: passed=" << passed << " failed=" << failed << " skipped=" << skipped << '\n';
    }

private:
    std::string suite_name_;
    bool stop_on_error_{false};
    std::vector<scenario_result> results_;
};

template<typename T, typename Describe>
[[nodiscard]] bool record_result(
    scenario_recorder& recorder,
    const std::string& step,
    mailxx::result<T>&& result,
    Describe&& describe_success)
{
    if (!result)
        return recorder.fail(step, result.error());

    if constexpr (std::is_void_v<T>)
        recorder.pass(step, describe_success());
    else
        recorder.pass(step, describe_success(*result));
    return true;
}

[[nodiscard]] mailxx::log::level parse_log_level(std::string value)
{
    value = lower_copy(std::move(value));
    if (value == "trace") return mailxx::log::level::trace;
    if (value == "debug") return mailxx::log::level::debug;
    if (value == "info") return mailxx::log::level::info;
    if (value == "warn") return mailxx::log::level::warn;
    if (value == "error") return mailxx::log::level::error;
    if (value == "fatal") return mailxx::log::level::fatal;
    if (value == "off") return mailxx::log::level::off;
    throw std::runtime_error("Unsupported log level: " + value);
}

