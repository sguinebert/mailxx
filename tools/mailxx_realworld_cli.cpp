template<typename Runner>
int run_suite(const std::string& suite_name, bool stop_on_error, int suite_timeout_sec, Runner&& runner)
{
    scenario_recorder recorder(suite_name, stop_on_error);
    mailxx::asio::io_context io;
    auto future = mailxx::asio::co_spawn(
        io,
        runner(recorder),
        mailxx::asio::use_future);
    std::thread io_thread([&io]()
    {
        io.run();
    });
    const auto wait_status = future.wait_for(std::chrono::seconds(suite_timeout_sec));
    if (wait_status == std::future_status::timeout)
    {
        (void)recorder.fail("suite_timeout", mailxx::make_error(
            mailxx::errc::net_timeout,
            "Suite timed out.",
            "timeout_seconds=" + std::to_string(suite_timeout_sec) + "\nA command likely blocked waiting on the server."));
        io.stop();
        io_thread.join();
        recorder.print_summary();
        return 124;
    }
    io_thread.join();
    const int exit_code = future.get();
    recorder.print_summary();
    return exit_code;
}

